export type PortfolioMediaType = 'image' | 'video' | 'gif' | 'diagram';

export type PortfolioMediaCategory =
  | 'featured'
  | 'procurement'
  | 'purchase-orders'
  | 'asset-management'
  | 'inventory'
  | 'budget'
  | 'task-management'
  | 'dashboards-reporting'
  | 'workflows'
  | 'other';

export interface PortfolioMediaItem {
  id: string;
  title: string;
  category: PortfolioMediaCategory;
  type: PortfolioMediaType;
  src: string;
  description: string;
  featured: boolean;
  displayOrder: number;
  relatedProject?: string;
  technology?: readonly string[];
  contribution?: string;
}

/**
 * Media under `public/media/`.
 * Featured items reuse the same `src` as the project file — no second copy.
 * Workflow diagrams live only under `featured/workflows/` (no payment project folder).
 */
export function getMediaForProject(projectId: string): PortfolioMediaItem[] {
  return portfolioMedia
    .filter((item) => item.relatedProject === projectId)
    .slice()
    .sort((a, b) => a.displayOrder - b.displayOrder);
}

export function getMediaById(id: string): PortfolioMediaItem | undefined {
  return portfolioMedia.find((item) => item.id === id);
}

export function getMediaByIds(ids: readonly string[]): PortfolioMediaItem[] {
  return ids
    .map((id) => getMediaById(id))
    .filter((item): item is PortfolioMediaItem => Boolean(item));
}

